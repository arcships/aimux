//! Result types for `do_generate` and `do_stream`.

use std::collections::HashMap;

use futures::Stream;
use serde::{Deserialize, Serialize};
use std::pin::Pin;
use ts_rs::TS;

use crate::error::AiMuxError;
pub use crate::shared::GeneratedFileData;
use crate::shared::RequestInfo;
use crate::stream_part::StreamPart;
use crate::tool::{RawToolCall, ToolResult};
use crate::types::{FinishReason, ProviderMetadata, ResponseMetadata, Usage, Warning};

/// A content item in the generation result.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub enum GenerateContent<C = RawToolCall, A = RawToolApprovalRequest, R = GeneratedFile> {
    /// Generated text.
    Text {
        text: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        provider_metadata: Option<ProviderMetadata>,
    },
    /// A tool call requested by the model. `input` is the provider's raw
    /// argument text; `generate_text` owns parsing, validation, and repair.
    ToolCall(C),
    /// A source / citation (e.g. URL citation from search-preview models).
    Source(Source),
    /// A reasoning / thinking segment produced by the model.
    Reasoning(ReasoningOutput),
    /// A file generated by the model (e.g. an image or document).
    File(GeneratedFile),
    /// A file generated as part of reasoning.
    ReasoningFile(R),
    /// Provider-specific content.
    Custom {
        kind: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        provider_metadata: Option<ProviderMetadata>,
    },
    /// Approval required for a provider-executed tool call.
    ToolApprovalRequest(A),
    /// A tool result from a provider-executed tool (e.g. xAI file_search,
    /// web_search). Emitted alongside the preceding `ToolCall` when the
    /// provider executes the tool server-side.
    ToolResult(ToolResult),
}

/// Content exposed by text generation after tool-call parsing.
pub type TextContent =
    GenerateContent<crate::tool::ToolCall, ToolApprovalRequestOutput, ReasoningFileOutput>;

// Export the user-facing alias without changing its Rust representation.
#[cfg(test)]
#[derive(TS)]
#[ts(export, rename = "TextContent", as = "TextContent")]
struct TextContentBinding;

/// Provider approval request for a provider-executed call.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct RawToolApprovalRequest {
    pub approval_id: String,
    pub tool_call_id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// Approval request exposed by text generation.
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct ToolApprovalRequestOutput {
    pub approval_id: String,
    pub tool_call: crate::tool::ToolCall,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub is_automatic: Option<bool>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub signature: Option<String>,
}

/// A source / citation (e.g. URL citation from search-preview models). The
/// payload of both `GenerateContent::Source` and `StreamPart::Source`, and the
/// element of the text results' `sources`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Source {
    pub id: String,
    pub source_type: String,
    pub url: Option<String>,
    pub title: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// A file generated by the model (e.g. an image or document). Mirrors the Vercel
/// AI SDK `file` content type: `data` is a tagged union covering base64 data,
/// or URL. The payload of both `GenerateContent::File` and
/// `StreamPart::File`, and the element of the text results' `files`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct GeneratedFile {
    pub data: GeneratedFileData,
    pub media_type: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// A reasoning / thinking segment produced by the model. Mirrors the Vercel AI
/// SDK `reasoning` content type; `provider_metadata` carries provider-specific
/// data such as the Anthropic thinking-block signature
/// (`providerMetadata.anthropic.signature`). The payload of
/// `GenerateContent::Reasoning` and the element of the text results' `reasoning`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct ReasoningOutput {
    pub text: String,
    pub provider_metadata: Option<ProviderMetadata>,
}

/// Text or a generated file produced during reasoning.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(untagged)]
#[ts(export)]
pub enum ReasoningPart {
    Text(ReasoningOutput),
    File(ReasoningFileOutput),
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct ReasoningFileOutput {
    pub file: GeneratedFile,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// Aggregated result of `stream_text().consume()` (M11). Mirrors
/// `GenerateTextResult`'s user-facing fields (without `raw`, since streaming
/// has no `GenerateResult` equivalent).
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct StreamTextResultAggregated {
    /// Ordered content from the last generation step.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub content: Vec<TextContent>,
    /// The generated text (concatenated `TextDelta`).
    pub text: String,
    /// Reasoning / thinking segments.
    #[serde(default)]
    pub reasoning: Vec<ReasoningPart>,
    /// Concatenated reasoning text.
    #[serde(default)]
    pub reasoning_text: String,
    /// Tool calls requested by the model.
    #[serde(default)]
    pub tool_calls: Vec<crate::tool::ToolCall>,
    /// Sources / citations.
    #[serde(default)]
    pub sources: Vec<Source>,
    /// Files generated by the model.
    #[serde(default)]
    pub files: Vec<GeneratedFile>,
    /// Why generation stopped.
    pub finish_reason: crate::types::FinishReason,
    /// Raw provider-specific finish reason string.
    #[serde(default)]
    pub raw_finish_reason: Option<String>,
    /// Token usage.
    #[serde(default)]
    pub usage: crate::types::Usage,
    /// Total token usage across all steps. In single-step mode (aimux's
    /// default), `total_usage` equals `usage`. Provided for AI SDK parity.
    #[serde(default)]
    pub total_usage: crate::types::Usage,
    /// Warnings from the provider.
    #[serde(default)]
    pub warnings: Vec<crate::types::Warning>,
    /// Provider-specific metadata from the Finish chunk.
    #[serde(default)]
    pub provider_metadata: Option<serde_json::Value>,
    /// Response metadata (id, timestamp, model_id) if emitted by the stream.
    #[serde(default)]
    pub response: Option<crate::types::ResponseMetadata>,
    /// Assistant messages ready to append for the next turn.
    #[serde(default)]
    pub response_messages: Vec<crate::message::ModelMessage>,
}

/// Result of `LanguageModel::do_generate` (non-streaming).
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[serde(from = "GenerateResultWire", into = "GenerateResultWire")]
#[ts(export, as = "GenerateResultWire")]
pub struct GenerateResult {
    /// Generated content items (text, tool calls, etc.).
    pub content: Vec<GenerateContent>,
    /// Why generation stopped.
    pub finish_reason: FinishReason,
    /// Token usage.
    pub usage: Usage,
    /// Warnings issued by the provider.
    pub warnings: Vec<Warning>,
    /// Provider-specific metadata.
    pub provider_metadata: Option<ProviderMetadata>,
    /// Optional response information.
    pub response: Option<GenerateResponse>,
    /// Optional request information.
    pub request: Option<RequestInfo>,
}

/// Result of `LanguageModel::do_stream` (streaming).
pub struct StreamResult {
    /// The stream of `StreamPart` items.
    pub stream: Pin<Box<dyn Stream<Item = Result<StreamPart, AiMuxError>> + Send>>,
    pub request: Option<RequestInfo>,
    pub response: Option<StreamResponse>,
}

impl std::fmt::Debug for StreamResult {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("StreamResult")
            .field("request", &self.request)
            .field("response", &self.response)
            .field("stream", &"<stream>")
            .finish()
    }
}

/// Response metadata and HTTP details from a generation call.
#[derive(Debug, Clone, Default, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct GenerateResponse {
    pub id: Option<String>,
    pub timestamp: Option<String>,
    pub model_id: Option<String>,
    pub headers: Option<HashMap<String, String>>,
    pub body: Option<serde_json::Value>,
}

impl From<ResponseMetadata> for GenerateResponse {
    fn from(metadata: ResponseMetadata) -> Self {
        Self {
            id: metadata.id,
            timestamp: metadata.timestamp,
            model_id: metadata.model_id,
            ..Default::default()
        }
    }
}

impl From<GenerateResponse> for ResponseMetadata {
    fn from(response: GenerateResponse) -> Self {
        Self {
            id: response.id,
            timestamp: response.timestamp,
            model_id: response.model_id,
        }
    }
}

/// HTTP details from a streaming call.
#[derive(Debug, Clone, Default, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct StreamResponse {
    pub headers: Option<HashMap<String, String>>,
}

// Preserve the established binding wire shape while exposing upstream's
// request and response objects to Rust callers.
#[derive(Serialize, Deserialize, TS)]
struct GenerateResultWire {
    content: Vec<GenerateContent>,
    finish_reason: FinishReason,
    usage: Usage,
    warnings: Vec<Warning>,
    provider_metadata: Option<ProviderMetadata>,
    #[ts(inline)]
    response: Option<GenerateResponseWire>,
    request_body: Option<serde_json::Value>,
    response_headers: Option<HashMap<String, String>>,
}

#[derive(Serialize, Deserialize, TS)]
struct GenerateResponseWire {
    id: Option<String>,
    timestamp: Option<String>,
    model_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    body: Option<serde_json::Value>,
}

impl From<GenerateResultWire> for GenerateResult {
    fn from(wire: GenerateResultWire) -> Self {
        Self {
            content: wire.content,
            finish_reason: wire.finish_reason,
            usage: wire.usage,
            warnings: wire.warnings,
            provider_metadata: wire.provider_metadata,
            request: wire
                .request_body
                .map(|body| RequestInfo { body: Some(body) }),
            response: wire
                .response
                .map(|meta| GenerateResponse {
                    id: meta.id,
                    timestamp: meta.timestamp,
                    model_id: meta.model_id,
                    headers: wire.response_headers.clone(),
                    body: meta.body,
                })
                .or_else(|| {
                    wire.response_headers.map(|headers| GenerateResponse {
                        headers: Some(headers),
                        ..Default::default()
                    })
                }),
        }
    }
}

impl From<GenerateResult> for GenerateResultWire {
    fn from(result: GenerateResult) -> Self {
        let response_headers = result
            .response
            .as_ref()
            .and_then(|response| response.headers.clone());
        Self {
            content: result.content,
            finish_reason: result.finish_reason,
            usage: result.usage,
            warnings: result.warnings,
            provider_metadata: result.provider_metadata,
            request_body: result.request.and_then(|request| request.body),
            response_headers,
            response: result.response.map(|meta| GenerateResponseWire {
                id: meta.id,
                timestamp: meta.timestamp,
                model_id: meta.model_id,
                body: meta.body,
            }),
        }
    }
}
