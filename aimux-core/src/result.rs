/// A file in a provider's output: `LanguageModelV4File` /
/// `LanguageModelV4ReasoningFile` (`provider`
/// `language-model/v4/language-model-v4-file.ts`), whose `data` is base64
/// data or a URL. The payload of the provider-level `GenerateContent::File` /
/// `ReasoningFile` and `StreamPart::File` / `ReasoningFile`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct LanguageModelFile {
    pub data: GeneratedFileData,
    pub media_type: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// A generated file (`ai` `generate-text/generated-file.ts:10-32`), the
/// element of the text results' `files`.
///
/// Its JSON is `{ base64, mediaType, providerMetadata? }`: the AI SDK's
/// `GeneratedFile` exposes the bytes as `base64` and as `uint8Array`, and the
/// JSON carries them once, as the base64 string. Text generation downloads a
/// provider's URL file before it builds one (`resolve-generated-file-data.ts`).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct GeneratedFile {
    /// The file's bytes, `base64` in the JSON.
    #[serde(rename = "base64")]
    pub data: FileBytes,
    pub media_type: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub provider_metadata: Option<ProviderMetadata>,
}

impl GeneratedFile {
    /// The file as a base64 string (`GeneratedFile.base64`).
    #[must_use]
    pub fn base64(&self) -> std::borrow::Cow<'_, str> {
        match &self.data {
            FileBytes::Base64(text) => std::borrow::Cow::Borrowed(text),
            FileBytes::Binary(bytes) => std::borrow::Cow::Owned(crate::wire::encode_base64(bytes)),
        }
    }

    /// The file's bytes (`GeneratedFile.uint8Array`).
    ///
    /// # Errors
    ///
    /// Returns the decode error when the base64 text is not base64.
    pub fn bytes(&self) -> Result<std::borrow::Cow<'_, [u8]>, base64::DecodeError> {
        match &self.data {
            FileBytes::Binary(bytes) => Ok(std::borrow::Cow::Borrowed(bytes)),
            FileBytes::Base64(text) => {
                crate::wire::decode_base64(text).map(std::borrow::Cow::Owned)
            }
        }
    }
}

/// A file part of text generation, `{ file, providerMetadata? }` under the
/// `file` or `reasoning-file` tag (`ai`
/// `generate-text/convert-language-model-content.ts:55-70`,
/// `stream-language-model-call.ts:569-590`). The part carries the provider
/// metadata; the file itself has none.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct GeneratedFileOutput {
    pub file: GeneratedFile,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// A reasoning / thinking segment produced by the model. Mirrors the Vercel AI
/// SDK `reasoning` content type; `provider_metadata` carries provider-specific
/// data such as the Anthropic thinking-block signature
/// (`providerMetadata.anthropic.signature`). The payload of
/// `GenerateContent::Reasoning` and the element of the text results' `reasoning`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct ReasoningOutput {
    pub text: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub provider_metadata: Option<ProviderMetadata>,
}

/// Text or a generated file produced during reasoning.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(tag = "type")]
#[ts(export)]
pub enum ReasoningPart {
    #[serde(rename = "reasoning")]
    Text(ReasoningOutput),
    #[serde(rename = "reasoning-file")]
    File(GeneratedFileOutput),
}

/// Aggregated result of `stream_text().consume()` (M11). Mirrors
/// `GenerateTextResult`'s user-facing fields (without `raw`, since streaming
/// has no `GenerateResult` equivalent).
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct StreamTextResultAggregated {
    /// Ordered content from the last generation step.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub content: Vec<TextContent>,
    /// The generated text (concatenated `TextDelta`).
    pub text: String,
    /// Reasoning / thinking segments.
    #[serde(default)]
    pub reasoning: Vec<ReasoningPart>,
    /// Concatenated reasoning text.
    #[serde(default)]
    pub reasoning_text: String,
    /// Tool calls requested by the model, each with its `type` tag.
    #[serde(default, with = "crate::wire::typed_vec")]
    #[ts(as = "Vec<crate::tool::TypedToolCall>")]
    pub tool_calls: Vec<crate::tool::ToolCall>,
    /// Sources / citations, each with its `type` tag.
    #[serde(default, with = "crate::wire::typed_vec")]
    #[ts(as = "Vec<TypedSource>")]
    pub sources: Vec<Source>,
    /// Files generated by the model.
    #[serde(default)]
    pub files: Vec<GeneratedFile>,
    /// Why generation stopped.
    pub finish_reason: crate::types::FinishReason,
    /// Raw provider-specific finish reason string.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub raw_finish_reason: Option<String>,
    /// Token usage.
    #[serde(default)]
    pub usage: crate::types::Usage,
    /// Total token usage across all steps. In single-step mode (aimux's
    /// default), `total_usage` equals `usage`. Provided for AI SDK parity.
    #[serde(default)]
    pub total_usage: crate::types::Usage,
    /// Warnings from the provider.
    #[serde(default)]
    pub warnings: Vec<crate::types::Warning>,
    /// Provider-specific metadata from the Finish chunk.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub provider_metadata: Option<ProviderMetadata>,
    /// Request information from the provider.
    #[serde(default)]
    pub request: RequestInfo,
    /// Response metadata and headers from the last step.
    #[serde(default)]
    pub response: ResponseInfo,
    /// Assistant messages ready to append for the next turn.
    #[serde(default)]
    pub response_messages: Vec<crate::message::ModelMessage>,
}

/// Result of `LanguageModel::do_generate` (non-streaming).
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct GenerateResult {
    /// Generated content items (text, tool calls, etc.).
    pub content: Vec<GenerateContent>,
    /// Why generation stopped.
    pub finish_reason: FinishReason,
    /// Token usage.
    pub usage: Usage,
    /// Warnings issued by the provider.
    pub warnings: Vec<Warning>,
    /// Provider-specific metadata.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub provider_metadata: Option<ProviderMetadata>,
    /// Optional request information for telemetry and debugging.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub request: Option<RequestInfo>,
    /// Optional response metadata, headers, and body.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub response: Option<ResponseInfo>,
}

/// Result of `LanguageModel::do_stream` (streaming).
pub struct StreamResult {
    /// The stream of `StreamPart` items.
    pub stream: Pin<Box<dyn Stream<Item = Result<StreamPart, AiMuxError>> + Send>>,
    /// Optional request information for telemetry and debugging.
    pub request: Option<RequestInfo>,
    /// Optional response headers.
    pub response: Option<StreamResponseInfo>,
}

impl std::fmt::Debug for StreamResult {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("StreamResult")
            .field("request", &self.request)
            .field("response", &self.response)
            .field("stream", &"<stream>")
            .finish()
    }
}
