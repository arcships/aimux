const PRESENCE: &str = r#"/** A field whose absence differs from an explicit JSON null. */
@JsonDeserialize(using = FieldPresence.Deserializer.class)
public final class FieldPresence<T> {
    private final boolean present;
    private final T value;

    private FieldPresence(boolean present, T value) {
        this.present = present;
        this.value = value;
    }

    public static <T> FieldPresence<T> absent() {
        return new FieldPresence<>(false, null);
    }

    public static <T> FieldPresence<T> of(T value) {
        return new FieldPresence<>(true, value instanceof JsonNode && ((JsonNode) value).isNull() ? null : value);
    }

    public boolean isPresent() {
        return present;
    }

    @JsonValue
    public T getValue() {
        return value;
    }

    /** Jackson's inclusion filter omits only absent fields. */
    public static final class Absent {
        @Override
        public boolean equals(java.lang.Object other) {
            return other instanceof FieldPresence && !((FieldPresence<?>) other).present;
        }

        @Override
        public int hashCode() {
            return 0;
        }
    }

    public static final class Deserializer extends JsonDeserializer<FieldPresence<?>>
        implements com.fasterxml.jackson.databind.deser.ContextualDeserializer {
        private final JavaType valueType;

        public Deserializer() {
            this(null);
        }

        private Deserializer(JavaType valueType) {
            this.valueType = valueType;
        }

        @Override
        public JsonDeserializer<?> createContextual(DeserializationContext context, BeanProperty property) {
            JavaType type = context.getContextualType();
            return new Deserializer(type.containedType(0));
        }

        @Override
        public FieldPresence<?> deserialize(com.fasterxml.jackson.core.JsonParser parser, DeserializationContext context)
            throws java.io.IOException {
            return FieldPresence.of(context.readValue(parser, valueType));
        }

        @Override
        public FieldPresence<?> getNullValue(DeserializationContext context) {
            return FieldPresence.of(null);
        }

        @Override
        public FieldPresence<?> getAbsentValue(DeserializationContext context) {
            return FieldPresence.absent();
        }
    }
}
"#;
