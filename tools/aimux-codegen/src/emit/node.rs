//! TypeScript wire declarations and DTO vector type metadata.
use super::Emitter;
use crate::model::{Codec, Field, Kind, Model, NamedType, Ty};
use std::{collections::BTreeMap, fmt::Write, path::PathBuf};

pub struct Node;
const WEB_DIR: &str = "tools/aimux-web/web/src/types/generated";

impl Emitter for Node {
    fn owned(&self) -> &'static [&'static str] {
        &[
            "bindings/node/src/generated/types.ts",
            "bindings/node/src/generated/dto_vectors.ts",
            WEB_DIR,
        ]
    }

    fn files(&self, model: &Model) -> Vec<(PathBuf, String)> {
        let mut out = String::from("// Generated by aimux-codegen. Do not edit.\n\n");
        let mut table = String::from(
            "// Generated by aimux-codegen. Do not edit.\nimport type * as T from './types.ts'\n\nexport interface DtoTypes {\n",
        );
        let mut tags = String::from(
            "export const dtoTags: Partial<Record<keyof DtoTypes, { tag: string; values: readonly string[] }>> = {\n",
        );
        let mut names = String::from("export const dtoTypeNames = [\n");
        for named in &model.types {
            write_declaration(&mut out, named);
            if let Kind::Tagged { tag, variants } = &named.kind {
                writeln!(
                    tags,
                    "  {}: {{ tag: {}, values: [{}] }},",
                    quote(&named.name),
                    quote(tag),
                    variants
                        .iter()
                        .map(|v| quote(&v.tag_value))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
                .unwrap();
            }
            writeln!(table, "  {}: T.{}", quote(&named.name), named.name).unwrap();
            writeln!(names, "  {},", quote(&named.name)).unwrap();
        }
        table.push_str("}\n\n");
        tags.push_str("}\n\n");
        names.push_str("] as const satisfies readonly (keyof DtoTypes)[]\n");
        table.push_str(&tags);
        table.push_str(&names);
        vec![
            (self.owned()[0].into(), out),
            (self.owned()[1].into(), table),
        ]
    }
}

/// Console wire types, one file per root, sharing core types through `@aimux/types`.
#[must_use]
pub fn web_files(model: &Model) -> Vec<(PathBuf, String)> {
    model
        .types
        .iter()
        .filter(|named| named.name.starts_with("Wire"))
        .map(|named| {
            let mut out = String::from("// Generated by aimux-codegen. Do not edit.\n");
            let mut imports: BTreeMap<String, Vec<String>> = BTreeMap::new();
            for name in type_refs(&named.kind) {
                if name == named.name {
                    continue;
                }
                let from = if name.starts_with("Wire") {
                    format!("./{name}")
                } else {
                    "@aimux/types".into()
                };
                imports.entry(from).or_default().push(name.to_owned());
            }
            for names in imports.values_mut() {
                names.sort();
                names.dedup();
            }
            for (from, names) in &imports {
                writeln!(out, "import type {{ {} }} from '{from}'", names.join(", ")).unwrap();
            }
            if !imports.is_empty() {
                out.push('\n');
            }
            write_declaration(&mut out, named);
            (format!("{WEB_DIR}/{}.ts", named.name).into(), out)
        })
        .collect()
}

fn write_declaration(out: &mut String, named: &NamedType) {
    let name = &named.name;
    docs(out, named.doc.as_deref(), "");
    match &named.kind {
        Kind::Struct { fields, .. } => {
            writeln!(out, "export interface {name} {{").unwrap();
            write_fields(out, fields, "  ");
            out.push_str("}\n\n");
        }
        Kind::StringEnum(values) => {
            writeln!(
                out,
                "export type {name} = {}\n",
                union(values.iter().map(|v| quote(v)))
            )
            .unwrap();
        }
        Kind::Tagged { tag, variants } => {
            writeln!(out, "export type {name} =").unwrap();
            for variant in variants {
                writeln!(
                    out,
                    "  | {{\n    {}: {}",
                    key(tag),
                    quote(&variant.tag_value)
                )
                .unwrap();
                write_fields(out, &variant.fields, "    ");
                out.push_str("  }\n");
            }
            out.push('\n');
        }
        Kind::Untagged(branches) => {
            writeln!(
                out,
                "export type {name} = {}\n",
                union(branches.iter().map(typescript))
            )
            .unwrap();
        }
        Kind::Alias(ty) => {
            writeln!(out, "export type {name} = {}\n", typescript(ty)).unwrap();
        }
    }
}

fn type_refs(kind: &Kind) -> Vec<&str> {
    let mut names = Vec::new();
    match kind {
        Kind::Struct { fields, .. } => {
            for field in fields {
                collect_refs(&field.ty, &mut names);
            }
        }
        Kind::Tagged { variants, .. } => {
            for variant in variants {
                for field in &variant.fields {
                    collect_refs(&field.ty, &mut names);
                }
            }
        }
        Kind::Untagged(branches) => {
            for ty in branches {
                collect_refs(ty, &mut names);
            }
        }
        Kind::Alias(ty) => collect_refs(ty, &mut names),
        Kind::StringEnum(_) => {}
    }
    names
}

fn collect_refs<'a>(ty: &'a Ty, names: &mut Vec<&'a str>) {
    match ty {
        Ty::Ref(name) => names.push(name),
        Ty::Array(inner) | Ty::Map(inner) | Ty::Nullable(inner) | Ty::Codec(_, inner) => {
            collect_refs(inner, names);
        }
        _ => {}
    }
}

fn quote(value: &str) -> String {
    serde_json::to_string(value).unwrap()
}

/// A property name, quoted only when it is not a plain identifier.
fn key(name: &str) -> String {
    let plain = name.chars().enumerate().all(|(i, c)| {
        c == '_' || c == '$' || c.is_ascii_alphabetic() || (i > 0 && c.is_ascii_digit())
    });
    if plain && !name.is_empty() {
        name.into()
    } else {
        quote(name)
    }
}

fn union(items: impl Iterator<Item = String>) -> String {
    let items: Vec<_> = items.collect();
    if items.is_empty() {
        "never".into()
    } else {
        items.join(" | ")
    }
}

fn docs(out: &mut String, doc: Option<&str>, indent: &str) {
    if let Some(doc) = doc {
        writeln!(out, "{indent}/**").unwrap();
        for line in doc.lines() {
            writeln!(out, "{indent} * {}", line.replace("*/", "* /")).unwrap();
        }
        writeln!(out, "{indent} */").unwrap();
    }
}

fn write_fields(out: &mut String, fields: &[Field], indent: &str) {
    for field in fields {
        docs(out, field.doc.as_deref(), indent);
        writeln!(
            out,
            "{indent}{}{}: {}",
            key(&field.json_name),
            if field.required { "" } else { "?" },
            typescript(&field.ty)
        )
        .unwrap();
    }
}

fn typescript(ty: &Ty) -> String {
    match ty {
        Ty::Ref(name) => name.clone(),
        Ty::Literal(value) => serde_json::to_string(value).unwrap(),
        Ty::String => "string".into(),
        Ty::Bool => "boolean".into(),
        Ty::Int { .. } | Ty::Float => "number".into(),
        Ty::Array(inner) => format!("Array<{}>", typescript(inner)),
        Ty::Map(inner) => format!("Record<string, {}>", typescript(inner)),
        Ty::Json => "unknown".into(),
        Ty::Nullable(inner) => format!("{} | null", typescript(inner)),
        Ty::Codec(Codec::Base64 | Codec::U64String | Codec::Timestamp, _) => "string".into(),
        Ty::Codec(Codec::Presence | Codec::Tagged, inner) => typescript(inner),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::normalize;
    use serde_json::json;

    #[test]
    fn wire_declarations_and_vector_tags() {
        let model = normalize(&json!({"input": {}, "output": {
            "Payload": {
                "type": "object", "description": "Payload */ documentation", "properties": {
                    "value": {"type": ["string", "null"], "x-aimux-codec": "presence"},
                    "bytes": {"type": "string", "x-aimux-codec": "base64"},
                    "id": {"type": "string", "x-aimux-codec": "u64-string"},
                    "count": {"type": "integer", "format": "uint64"}
                }, "required": ["bytes", "id", "count"]
            },
            "Event": {"oneOf": [
                {"type": "object", "properties": {"kind": {"const": "one"}, "body": {"$ref": "#/typeDefs/output/Payload"}}, "required": ["kind", "body"]},
                {"type": "object", "properties": {"kind": {"const": "two"}}, "required": ["kind"]}
            ]},
            "Ordered": {"anyOf": [{"type": "string"}, {"type": "number"}], "x-aimux-codec": "ordered-untagged"}
        }})).unwrap();
        let files = Node.files(&model);
        assert_eq!(files, Node.files(&model));
        let out = &files[0].1;
        assert!(out.contains("Payload * / documentation"));
        assert!(out.contains("value?: string | null"));
        assert!(out.contains("count: number"));
        assert!(out.contains("bytes: string"));
        assert!(out.contains("id: string"));
        assert!(out.contains("export type Ordered = string | number"));
        assert!(out.contains("kind: \"one\"\n    body: Payload"));
        assert!(
            files[1]
                .1
                .contains("\"Event\": { tag: \"kind\", values: [\"one\", \"two\"] }")
        );
        assert!(files[1].1.contains("\"Payload\": T.Payload"));
    }

    #[test]
    fn web_files_emit_wire_roots_and_import_shared_types() {
        let model = normalize(&json!({"input": {}, "output": {
            "Payload": {"type": "object", "properties": {"n": {"type": "integer"}}, "required": ["n"]},
            "WireTool": {"type": "object", "properties": {
                "name": {"type": "string"},
                "parameters": true
            }, "required": ["name", "parameters"]},
            "WireMessage": {"type": "object", "description": "A chat message", "properties": {
                "role": {"type": "string"},
                "part": {"$ref": "#/typeDefs/output/Payload"},
                "tool": {"$ref": "#/typeDefs/output/WireTool"}
            }, "required": ["role", "part", "tool"]}
        }})).unwrap();
        let files = web_files(&model);
        assert_eq!(files, web_files(&model));
        let paths: Vec<_> = files
            .iter()
            .map(|(path, _)| path.to_str().unwrap())
            .collect();
        assert_eq!(
            paths,
            [
                "tools/aimux-web/web/src/types/generated/WireMessage.ts",
                "tools/aimux-web/web/src/types/generated/WireTool.ts"
            ]
        );
        assert!(
            files[0]
                .1
                .contains("import type { Payload } from '@aimux/types'")
        );
        assert!(
            files[0]
                .1
                .contains("import type { WireTool } from './WireTool'")
        );
        assert!(files[0].1.contains("A chat message"));
        assert!(files[1].1.contains("parameters: unknown"));
        assert!(!files[1].1.contains("import type"));
    }
}
