#!/usr/bin/env python3
"""Merge a `libaimux_ffi.a` into one object rooted at its C API and strip the
local symbols (RFC-0043 §5.3 S1c).

    merge_archive.py <archive> [--out <archive>]

rustc gives every function its own section, so a staticlib's members spend a
third of their bytes on section headers, section-name tables and string
tables that the consumer's linker only ever reads to throw most of them away.
This script does that work once, at release time:

1. the exported C API is read twice and must agree: the `aimux_*` functions
   declared in `aimux-ffi/include/aimux.h`, and the `aimux_*` symbols the
   `aimux_ffi` members define (`llvm-nm`);
2. on ELF and COFF, `ld -r --gc-sections -u <export>...` links every member
   into one relocatable object and drops every section no export reaches
   (GNU ld, the linker the archive's consumers use: the file it writes is what
   they read). A COFF archive is merged without `--gc-sections`: GNU ld's PE
   garbage collection in a relocatable link drops the `.text$f` of an
   unreferenced gcc-built function (ring's C code) but keeps its
   `.pdata$f`/`.xdata$f`, whose relocations then overflow in the consumer's
   link ("relocation truncated to fit: IMAGE_REL_AMD64_ADDR32NB"), and it
   removed 77 KB of a 42 MB object in the first place;
   on Mach-O, Apple `ld -r -exported_symbols_list <list> -filelist <members>`
   merges all members into one object (dropping per-member symbol/string/header
   tables), keeping the `_aimux_*` C API exports plus `_rust_eh_personality`
   when defined in the archive (`__LD,__compact_unwind` references it and
   `strip -S -x` would remove it once `ld -r` internalizes unexported globals);
   bitcode must already be stripped (`check_native_artifact.py --strip-bitcode`);
3. `llvm-strip --strip-unneeded` (or Apple `strip -S -x` on Mach-O) removes
   the debug and local symbols the merged object no longer needs for
   relocation;
4. `llvm-ar` (or system `ar rcs` on Mach-O) writes the archive back with the
   merged object as its first member, named `aimux_ffi.merged.o` so
   `check_native_artifact.py` still finds a workspace crate among the
   members; an archive that already starts with that member is left alone, so
   the step can run twice.

A windows-gnu archive also carries import-library members (`<dll>.dllh.o`,
`<dll>.dlls00000.o`, `<dll>.dllt.o`: one import descriptor, stub and
terminator per DLL and symbol, generated by rustc for std's `raw-dylib`
imports and bundled from the `windows-targets` import library). Several
copies of the same stub coexist in the archive (std and windows-targets both
import `kernel32!Sleep`), which a normal link tolerates because it pulls the
first member that defines a symbol and never looks at the rest, but which
`ld -r` of every member rejects as a multiple definition. Those members are
not code of ours and gain nothing from merging, so they are kept as they
are, after the merged object, and the consumer's linker pulls them as it
does today.

The linked program is unchanged: the same code, the same exports. `AIMUX_LD`,
`AIMUX_STRIP`, `AIMUX_AR`, and `AIMUX_NM` override the linker and binutils
(falling back to Apple `ld`/`strip`/`ar`/`nm` on Mach-O and
`check_native_artifact.find_llvm_tool` on ELF/COFF).
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_native_artifact as check  # noqa: E402

MERGED_MEMBER = "aimux_ffi.merged.o"


def header_exports(root):
    """`aimux_*` functions declared in aimux.h, comments removed first so a
    name mentioned in a `/* ... */` or `//` comment is not taken for one."""
    text = (root / "aimux-ffi" / "include" / "aimux.h").read_text(encoding="utf-8")
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return set(re.findall(r"(?<![\w(])(aimux_\w+)\s*\(", text))


def defined_exports(nm, members):
    """`aimux_*` symbols defined by the workspace crate `aimux_ffi`'s members
    (`members` are (path on disk, member name) pairs)."""
    names = set()
    for path, name in members:
        if check.crate_of(name) != "aimux_ffi":
            continue
        out = subprocess.run(
            [nm, "--defined-only", "--extern-only", str(path)], check=True, capture_output=True, text=True
        ).stdout
        for line in out.splitlines():
            parts = line.split()
            if parts and re.fullmatch(r"_?aimux_\w+", parts[-1]):
                names.add(parts[-1].lstrip("_") if parts[-1].startswith("_aimux_") else parts[-1])
    return names


def has_defined_symbol(nm, members, symbol):
    """True if any object in `members` defines external `symbol`."""
    paths = [str(path) for path, _ in members]
    for i in range(0, len(paths), 100):
        out = subprocess.run(
            [nm, "--defined-only", "--extern-only", *paths[i : i + 100]],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
        for line in out.splitlines():
            parts = line.split()
            if parts and parts[-1] == symbol:
                return True
    return False


def is_import_member(body):
    """True for a COFF import-library member (descriptor, stub or terminator)."""
    if len(body) < 20 or check.struct.unpack_from("<H", body)[0] not in check.COFF_MACHINES:
        return False
    return any(name.startswith(".idata$") for name, _ in check.coff_sections(body))


MACHO_PLATFORMS = {
    1: "macos",
    2: "ios",
    3: "tvos",
    4: "watchos",
    7: "ios-simulator",
    8: "tvos-simulator",
    9: "watchos-simulator",
}
LC_VERSION_MIN_PLATFORMS = {0x24: 1, 0x25: 2, 0x2F: 3, 0x30: 4}
LC_VERSION_MIN_SIM_PLATFORMS = {0x25: 7, 0x2F: 8, 0x30: 9}
X86_CPU_TYPES = {7, 0x01000007}  # CPU_TYPE_I386, CPU_TYPE_X86_64


def format_macho_version(ver):
    major, minor, patch = (ver >> 16) & 0xFFFF, (ver >> 8) & 0xFF, ver & 0xFF
    return f"{major}.{minor}.{patch}" if patch else f"{major}.{minor}"


def macho_platform_flags(bodies):
    """Return `-platform_version <platform> <max_minos> <max_sdk>` from members."""
    platforms = set()
    max_minos = 0
    max_sdk = 0
    for body in bodies:
        if body[:4] not in check.MACHO_MAGICS:
            continue
        end, bits = check.MACHO_MAGICS[body[:4]]
        hdr_size = 32 if bits == 64 else 28
        if len(body) < hdr_size:
            continue
        cputype = check.struct.unpack_from(end + "I", body, 4)[0]
        ncmds, sizeofcmds = check.struct.unpack_from(end + "II", body, 16)
        limit = min(len(body), hdr_size + sizeofcmds)
        offset = hdr_size
        for _ in range(ncmds):
            if offset + 8 > limit:
                break
            cmd, cmdsize = check.struct.unpack_from(end + "II", body, offset)
            if cmdsize < 8 or offset + cmdsize > limit:
                break
            if cmd == 0x32 and cmdsize >= 24:  # LC_BUILD_VERSION
                plat, minos, sdk = check.struct.unpack_from(end + "III", body, offset + 8)
            elif cmd in LC_VERSION_MIN_PLATFORMS and cmdsize >= 16:
                plat = (
                    LC_VERSION_MIN_SIM_PLATFORMS.get(cmd, LC_VERSION_MIN_PLATFORMS[cmd])
                    if cputype in X86_CPU_TYPES
                    else LC_VERSION_MIN_PLATFORMS[cmd]
                )
                minos, sdk = check.struct.unpack_from(end + "II", body, offset + 8)
            else:
                offset += cmdsize
                continue
            platforms.add(plat)
            max_minos = max(max_minos, minos)
            max_sdk = max(max_sdk, sdk)
            offset += cmdsize
    if len(platforms) != 1:
        return []
    platform_name = MACHO_PLATFORMS.get(next(iter(platforms)))
    if not platform_name or not max_minos:
        return []
    return ["-platform_version", platform_name, format_macho_version(max_minos), format_macho_version(max_sdk)]


def object_format(data):
    for _, body in check.archive_members(data):
        if body[:4] == b"\x7fELF":
            return "elf"
        if body[:4] in check.MACHO_MAGICS:
            return "macho"
        if len(body) >= 20 and check.struct.unpack_from("<H", body)[0] in check.COFF_MACHINES:
            return "coff"
    sys.exit("archive has no ELF, Mach-O or COFF member")


def main(argv):
    out = None
    if "--out" in argv:
        i = argv.index("--out")
        out = Path(argv[i + 1])
        argv = argv[:i] + argv[i + 2 :]
    if len(argv) != 1:
        sys.exit(__doc__)
    path = Path(argv[0])
    out = out or path
    root = Path(__file__).resolve().parent.parent
    data = path.read_bytes()
    if not data.startswith(b"!<arch>\n"):
        sys.exit(f"{path}: not an archive")
    crates = check.workspace_crates(root)
    names = [name for name, body in check.archive_members(data) if check.member_report(body) is not None]
    if names[:1] == [MERGED_MEMBER]:
        if not check.check_archive(path, data, crates, expect_no_bitcode=True):
            sys.exit(1)
        print(f"{path}: already merged ({len(data)} bytes)")
        if out != path:
            shutil.copyfile(path, out)
        return
    fmt = object_format(data)
    ld = os.environ.get("AIMUX_LD") or shutil.which("ld") or sys.exit("no ld on PATH (set AIMUX_LD)")
    if fmt == "macho":
        strip = (
            os.environ.get("AIMUX_STRIP")
            or shutil.which("strip")
            or sys.exit("no strip on PATH (set AIMUX_STRIP)")
        )
        ar = os.environ.get("AIMUX_AR") or shutil.which("ar") or sys.exit("no ar on PATH (set AIMUX_AR)")
        nm = os.environ.get("AIMUX_NM") or shutil.which("nm") or check.find_llvm_tool("nm")
    else:
        nm, strip, ar = (check.find_llvm_tool(t) for t in ("nm", "strip", "ar"))

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        members, member_bodies, imports = [], [], []
        for i, (name, body) in enumerate(check.archive_members(data)):
            if check.member_report(body) is None:
                continue
            # One directory per member: names repeat inside the archive, and
            # llvm-ar names a member after its file.
            member = tmp / "members" / f"{i:05d}" / Path(name).name
            member.parent.mkdir(parents=True)
            member.write_bytes(body)
            if is_import_member(body):
                imports.append((member, name))
            else:
                members.append((member, name))
                member_bodies.append(body)
        exports = defined_exports(nm, members)
        declared = header_exports(root)
        if exports != declared:
            sys.exit(
                f"{path}: exported C API differs from aimux-ffi/include/aimux.h: "
                f"only in archive {sorted(exports - declared)}, only in header {sorted(declared - exports)}"
            )
        print(f"  {len(members)} members, {len(exports)} exports: {' '.join(sorted(exports))}")
        if imports:
            print(f"  {len(imports)} import-library members kept as they are")

        merged = tmp / MERGED_MEMBER
        merged_archive = tmp / "merged.a"
        if fmt == "macho":
            kept_symbols = [f"_{export}" for export in sorted(exports)]
            # __LD,__compact_unwind references _rust_eh_personality across merged
            # objects; if ld -r internalizes it, strip -S -x drops it and breaks
            # the downstream clang/ld64 link.
            if has_defined_symbol(nm, members, "_rust_eh_personality"):
                kept_symbols.append("_rust_eh_personality")
            exports_file = tmp / "exports.txt"
            exports_file.write_text("\n".join(kept_symbols) + "\n", encoding="utf-8")
            filelist = tmp / "members.filelist"
            filelist.write_text("\n".join(str(m) for m, _ in members) + "\n", encoding="utf-8")
            platform_flags = macho_platform_flags(member_bodies)
            subprocess.run(
                [
                    ld,
                    "-r",
                    *platform_flags,
                    "-exported_symbols_list",
                    str(exports_file),
                    "-filelist",
                    str(filelist),
                    "-o",
                    str(merged),
                ],
                check=True,
            )
            print(
                f"  before merge: {len(data)} bytes; merged object {merged.stat().st_size} bytes "
                f"({ld} -r -exported_symbols_list)"
            )
            subprocess.run([strip, "-S", "-x", str(merged)], check=True)
            print(f"  after strip -S -x: {merged.stat().st_size} bytes ({strip})")
            kept = defined_exports(nm, [(merged, MERGED_MEMBER)])
            if kept != declared:
                sys.exit(
                    f"{path}: the merged object does not define the C API after the strip: "
                    f"missing {sorted(declared - kept)}, extra {sorted(kept - declared)}"
                )
            subprocess.run([ar, "rcs", str(merged_archive), str(merged)], check=True)
        else:
            # Thousands of member paths overflow the Windows command line (WinError 206),
            # so the inputs go through a GNU ld response file. Forward slashes keep the
            # paths out of the response-file backslash escaping; mingw ld accepts them.
            response = tmp / "members.rsp"
            lines = [f"-u {export}" for export in sorted(exports)]
            lines += [f'"{m.as_posix()}"' for m, _ in members]
            response.write_text("\n".join(lines) + "\n", encoding="utf-8")
            gc = ["--gc-sections"] if fmt == "elf" else []  # see the module docstring for COFF
            subprocess.run([ld, "-r", *gc, f"@{response}", "-o", str(merged)], check=True)
            print(
                f"  before merge: {len(data)} bytes; merged object {merged.stat().st_size} bytes "
                f"({' '.join([ld, '-r', *gc])})"
            )
            subprocess.run([strip, "--strip-unneeded", str(merged)], check=True)
            print(f"  after strip --strip-unneeded: {merged.stat().st_size} bytes ({strip})")
            kept = defined_exports(nm, [(merged, MERGED_MEMBER)])
            if kept != declared:
                sys.exit(
                    f"{path}: the merged object does not define the C API after the strip: "
                    f"missing {sorted(declared - kept)}, extra {sorted(kept - declared)}"
                )

            archive_response = tmp / "archive.rsp"
            archive_response.write_text(
                "\n".join(f'"{p.as_posix()}"' for p in [merged] + [m for m, _ in imports]) + "\n",
                encoding="utf-8",
            )
            subprocess.run([ar, "rcs", "--format=gnu", str(merged_archive), f"@{archive_response}"], check=True)
        result = merged_archive.read_bytes()
        if not check.check_archive(out, result, crates, expect_no_bitcode=True):
            sys.exit(1)
        shutil.copyfile(merged_archive, out)

    print(f"size {out} {len(result)} bytes")


if __name__ == "__main__":
    main(sys.argv[1:])
