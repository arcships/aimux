# Helpers
# ─────────────────────────────────────────────────────────────────────────────

Prompt = Union[str, List[ModelMessage], List[Dict[str, Any]]]


def _prompt_to_json(prompt: Prompt) -> str:
    """Build the JSON prompt string expected by the native layer.

    A bare string is emitted as a JSON string (→ ``ModelPrompt::Text``). A list
    of messages is wrapped as ``{"prompt": [...]}`` (→ ``ModelPrompt::Messages``).
    ``ModelMessage`` instances are serialized with ``mode="json"`` so nested
    models become JSON primitives.
    """
    if isinstance(prompt, str):
        return json.dumps(prompt)
    if not isinstance(prompt, list):
        raise TypeError(
            f"prompt must be str or list of messages, got {type(prompt).__name__}"
        )
    msgs = [
        m.model_dump(mode="json", exclude_none=True, by_alias=True)
        if isinstance(m, BaseModel)
        else m
        for m in prompt
    ]
    return json.dumps({"prompt": msgs})


def _opts_to_json(options: Optional[GenerateTextOptions]) -> Optional[str]:
    """Serialize options to the JSON string expected by the native layer."""
    if options is None:
        return None
    if not isinstance(options, GenerateTextOptions):
        raise TypeError(
            "options must be a GenerateTextOptions instance, got "
            f"{type(options).__name__}"
        )
    # ``exclude_none`` mirrors Rust's ``#[serde(skip_serializing_if = "Option::is_none")]``
    # on the inner struct fields, producing clean payloads (absent == None for the
    # Rust deserializer). ``by_alias`` emits the ``schema`` field of the JSON
    # response-format body and the camelCase keys of every model.
    return options.model_dump_json(exclude_none=True, by_alias=True)


def _repair_adapter(options: Optional[GenerateTextOptions]):
    """Bridge the typed repair function to the JSON-level loop in ``_repair``."""
    fn = options.repair_tool_call if options is not None else None
    if fn is None:
        return None

    def adapter(context: dict) -> Optional[dict]:
        typed = ToolCallRepairContext.model_validate(context)
        replacement = _repair.run_hook(fn, typed)
        if replacement is None:
            return None
        return replacement.model_dump(mode="json", exclude_none=True, by_alias=True)

    return adapter


