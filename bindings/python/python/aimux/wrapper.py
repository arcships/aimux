"""Typed wrapper for the aimux Python binding.

This layer sits *on top* of the native PyO3 ``Model.generate_text`` /
``Model.stream_text`` methods (which exchange JSON strings) and exposes a
typed API: inputs and outputs are Pydantic models / native Python objects, so
callers never have to ``json.dumps`` / ``json.loads`` by hand.

The native (raw) JSON-string API in :mod:`aimux` is left untouched — this
module is an additional, optional layer::

    from aimux.wrapper import generate_text, GenerateTextOptions, ModelMessage

The Pydantic models mirror the Rust core types in ``aimux-core/src/`` (see
``bindings/node/src/types/*.ts`` for the field structure generated by ts-rs).
Field names are ``snake_case`` to match the Rust serde wire format; the few
camelCase exceptions required by the wire format (``toolName``) are handled
internally by custom serializers.
"""

