class _ResponseFormatJsonBody(BaseModel):
    model_config = ConfigDict(populate_by_name=True)

    schema_: Optional[Any] = Field(default=None, alias="schema")
    name: Optional[str] = None
    description: Optional[str] = None


class ResponseFormat(RootModel[Union[Literal["Text"], _ResponseFormatJsonBody]]):
    """How the model should format its response (Rust ``ResponseFormat``).

    Wire format: ``"Text"`` or ``{"Json": {"schema": ..., "name": ..., "description": ...}}``.
    """

    root: Union[Literal["Text"], _ResponseFormatJsonBody]

    @model_validator(mode="before")
    @classmethod
    def _unwrap(cls, data: Any) -> Any:
        if isinstance(data, dict) and len(data) == 1:
            (tag, payload), = data.items()
            if tag == "Text":
                return "Text"
            if tag == "Json":
                return payload if isinstance(payload, dict) else {}
        return data

    @model_serializer(mode="wrap")
    def _ser(self, handler):  # type: ignore[no-untyped-def]
        out = handler(self)
        if isinstance(out, dict):
            return {"Json": out}
        return out  # bare "Text"


