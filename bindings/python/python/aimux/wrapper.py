def generate_text(
    model: Model,
    prompt: Prompt,
    options: Optional[GenerateTextOptions] = None,
) -> GenerateTextResult:
    """Generate text (non-streaming), returning a typed result.

    Args:
        model: A model instance from ``openai()``, ``anthropic()``, etc.
        prompt: A string or a list of ``ModelMessage`` / message dicts.
        options: Optional typed generation options.

    Returns:
        A :class:`GenerateTextResult` with ``.text``, ``.tool_calls``,
        ``.finish_reason``, ``.usage``, ``.warnings`` and ``.raw``.
    """
    prompt_json = _prompt_to_json(prompt)
    opts_json = _opts_to_json(options)
    result_json = model.generate_text(prompt_json, opts_json)
    repair = _repair_adapter(options)
    if repair is not None:
        result_json = _repair.repair_result(result_json, prompt_json, opts_json, repair)
    return GenerateTextResult.model_validate_json(result_json)


def stream_text(
    model: Model,
    prompt: Prompt,
    options: Optional[GenerateTextOptions] = None,
) -> Iterator[dict]:
    """Stream text from a model, yielding parsed ``StreamPart`` dicts.

    Each yielded item is the dict form produced by the Rust core, tagged by
    ``type``, e.g. ``{"type": "text-delta", "id": ..., "delta": ...}``. For
    typed access, pass the dict through :func:`parse_stream_part`.

    Usage::

        for part in stream_text(model, "Write a haiku about Rust."):
            if part["type"] == "text-delta":
                print(part["delta"], end="")
    """
    prompt_json = _prompt_to_json(prompt)
    opts_json = _opts_to_json(options)
    repair = _repair_adapter(options)
    for part_json in model.stream_text(prompt_json, opts_json):
        if repair is not None:
            part_json = _repair.repair_stream_part(
                part_json, prompt_json, opts_json, repair
            )
        yield json.loads(part_json)


_STREAM_PART = TypeAdapter(StreamPart)


def parse_stream_part(part: dict) -> BaseModel:
    """Validate a yielded stream-part dict into its typed model (see ``StreamPart``)."""
    return _STREAM_PART.validate_python(part)


def generate_text_as_openai(
    model: Model,
    prompt: Prompt,
    options: Optional[GenerateTextOptions] = None,
) -> ChatCompletion:
    """Generate text and return the result as an OpenAI Chat Completion.

    Identical to :func:`generate_text` except the result is a
    :class:`ChatCompletion` (OpenAI ``chat.completion`` object) rather than a
    :class:`GenerateTextResult`. Works with any provider.

    Args:
        model: A model instance from ``openai()``, ``anthropic()``, etc.
        prompt: A string or a list of ``ModelMessage`` / message dicts.
        options: Optional typed generation options.

    Returns:
        A :class:`ChatCompletion` with ``.id``, ``.choices``, ``.usage``, …

    With ``options.repair_tool_call``, invalid calls are repaired on the
    native result first and the completion is converted from it, so its
    ``tool_calls`` carry the repaired arguments.
    """
    prompt_json = _prompt_to_json(prompt)
    opts_json = _opts_to_json(options)
    return ChatCompletion.model_validate_json(
        _repair.generate_openai_with_repair(model, prompt_json, opts_json, _repair_adapter(options))
    )


def stream_text_as_openai(
    model: Model,
    prompt: Prompt,
    options: Optional[GenerateTextOptions] = None,
) -> Iterator[ChatCompletionChunk]:
    """Stream text as OpenAI Chat Completion chunks.

    Identical to :func:`stream_text` except each yielded item is a typed
    :class:`ChatCompletionChunk` (OpenAI ``chat.completion.chunk`` object).
    Works with any provider.

    Stream options (``include_usage``, ``include_reasoning``) are read from
    ``options.provider_options.openai.stream_options`` (both default to ``True``).

    Usage::

        for chunk in stream_text_as_openai(model, "Write a haiku about Rust."):
            if chunk.choices and chunk.choices[0].delta.content:
                print(chunk.choices[0].delta.content, end="")
    """
    prompt_json = _prompt_to_json(prompt)
    opts_json = _opts_to_json(options)
    for chunk_json in model.stream_text_as_openai(prompt_json, opts_json):
        yield ChatCompletionChunk.model_validate_json(chunk_json)
