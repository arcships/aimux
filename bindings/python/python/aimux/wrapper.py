# ─────────────────────────────────────────────────────────────────────────────
# External-tag enums (Rust serde default for enums)
#
# Rust serializes these as ``{"Variant": {fields}}``. Pydantic discriminated
# unions use an *internal* tag, so each enum is modelled as a ``RootModel``
# over a discriminated union with a ``type`` field, plus a before-validator
# that converts the external tag into the internal discriminator and a wrap
# serializer that converts it back.
# ─────────────────────────────────────────────────────────────────────────────

def _external_tag_before(data: Any) -> Any:
    """Convert ``{"Variant": {payload}}`` → ``{"type": "Variant", **payload}``.

    Passes other shapes through unchanged (so already-internal-tagged data and
    scalars still validate).
    """
    if isinstance(data, dict) and len(data) == 1:
        (tag, payload), = data.items()
        if isinstance(payload, dict):
            return {"type": tag, **payload}
    return data


def _external_tag_serializer(out: Any) -> Any:
    """Convert ``{"type": "Variant", **fields}`` → ``{"Variant": {fields}}``."""
    if isinstance(out, dict) and "type" in out:
        tag = out.pop("type")
        return {tag: out}
    return out


