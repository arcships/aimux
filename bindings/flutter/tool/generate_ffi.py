#!/usr/bin/env python3
"""Generate the versioned ops ABI primitives from a C header; reject unexpected layouts."""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('header', nargs='?', type=pathlib.Path, default=ROOT.parents[1] / 'aimux-ffi/include/aimux.h')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = re.sub(r'/\*.*?\*/|//[^\n]*', '', args.header.read_text(), flags=re.S)
types = {
    'void': ('Void', 'void'), 'uint32_t': ('Uint32', 'int'),
    'uint64_t': ('Uint64', 'int'), 'int64_t': ('Int64', 'int'),
    'int32_t': ('Int32', 'int'), 'size_t': ('UintPtr', 'int'),
    'char*': ('Pointer<Utf8>', 'Pointer<Utf8>'),
    'char**': ('Pointer<Pointer<Utf8>>', 'Pointer<Pointer<Utf8>>'),
    'void*': ('Pointer<Void>', 'Pointer<Void>'),
    'uint8_t*': ('Pointer<Uint8>', 'Pointer<Uint8>'),
    'int32_t*': ('Pointer<Int32>', 'Pointer<Int32>'),
    'aimux_error_t*': ('Pointer<Void>', 'Pointer<Void>'),
    'aimux_event_cb': ('Pointer<NativeFunction<NativeEvent>>', 'Pointer<NativeFunction<NativeEvent>>'),
}
expected = {
    'abi_version': ('uint32_t', []),
    'manifest_json': ('aimux_error_t*', ['char**']),
    'call': ('aimux_error_t*', ['uint64_t', 'char*', 'char*', 'uint64_t', 'char**']),
    'stream': ('aimux_error_t*', ['uint64_t', 'char*', 'char*', 'uint64_t', 'aimux_event_cb', 'void*']),
    'operation_push': ('aimux_error_t*', ['uint64_t', 'uint8_t*', 'size_t']),
    'operation_next_part': ('aimux_error_t*', ['uint64_t', 'int64_t', 'char**', 'int32_t*']),
    'handle_finalizer': ('void', ['void*']),
    'abort': ('void', ['uint64_t']), 'drop': ('void', ['uint64_t']),
    'free_string': ('void', ['char*']), 'error_free': ('void', ['aimux_error_t*']),
    'error_code': ('int32_t', ['aimux_error_t*']),
    'error_message': ('char*', ['aimux_error_t*']),
    'error_json': ('char*', ['aimux_error_t*']),
}

def normalized(value):
    return re.sub(r'\s+', '', value.replace('const', ''))

found = {}
for match in re.finditer(r'\b(uint32_t|int32_t|void|char\s*\*|aimux_error_t\s*\*)\s*(aimux_\w+)\s*\((.*?)\)\s*;', source, re.S):
    name = match[2].removeprefix('aimux_')
    if name not in expected:
        continue
    params = [] if match[3].strip() in ('void', '') else match[3].split(',')
    params = [normalized(re.sub(r'\b\w+\s*$', '', p.strip())) for p in params]
    found[name] = (normalized(match[1]), params)
for name, signature in expected.items():
    if found.get(name) != signature:
        raise SystemExit(f'header mismatch for aimux_{name}: expected {signature}, got {found.get(name)}')
lines = [
    '// Generated by tool/generate_ffi.py from the shared C header. Do not edit.',
    "import 'dart:ffi';", "import 'package:ffi/ffi.dart';", '',
    'typedef NativeEvent = Void Function(Pointer<Utf8>, Pointer<Void>);', '',
    'final class OpsBindings {', '  final DynamicLibrary library;',
    '  OpsBindings(this.library);', '',
]
for name, (result, params) in expected.items():
    dart_name = re.sub(r'_([a-z])', lambda m: m[1].upper(), name)
    native = f'{types[result][0]} Function({", ".join(types[p][0] for p in params)})'
    dart = f'{types[result][1]} Function({", ".join(types[p][1] for p in params)})'
    lines.append(f"  late final {dart_name} = library.lookupFunction<{native}, {dart}>('aimux_{name}');")
lines.extend(['}', ''])
output = '\n'.join(lines)
target = ROOT / 'lib/src/ffi.g.dart'
if args.check:
    if (ROOT / 'native/aimux_ops.h').read_text() != args.header.read_text():
        raise SystemExit('packaged header differs; run tool/generate_ffi.py')
    if target.read_text() != output:
        raise SystemExit('generated declarations differ; run tool/generate_ffi.py')
else:
    target.write_text(output)
    (ROOT / 'native/aimux_ops.h').write_text(args.header.read_text())
